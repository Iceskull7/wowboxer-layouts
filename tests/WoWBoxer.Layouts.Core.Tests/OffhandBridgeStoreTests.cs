using System.Text;
using WoWBoxer.Layouts.Core;

namespace WoWBoxer.Layouts.Core.Tests;

public sealed class OffhandBridgeStoreTests : IDisposable
{
    private readonly DirectoryInfo _root = Directory.CreateTempSubdirectory();
    private const string Stub = "-- packaged placeholder\r\nOffhandCompanionTopology = nil\r\n";
    private const string Bridge = "-- Generated by WoWBoxer Offhand.\nOffhandCompanionTopology = { schema = 1 }\n";
    private const string Manifest = "## X-Offhand-Companion-Protocol: 1\n## X-Offhand-Topology-Schemas: 1,2,3\nCore\\CompanionTopology.lua\n";

    private (string Exe, string Topology) Client(string flavor, string? manifest = Manifest)
    {
        var install = Directory.CreateDirectory(Path.Combine(_root.FullName, flavor)).FullName;
        var exe = Path.Combine(install, "Wow.exe");
        File.WriteAllBytes(exe, []);
        var addon = Path.Combine(install, "Interface", "AddOns", "Offhand");
        var topology = Path.Combine(addon, "Core", "CompanionTopology.lua");
        if (manifest is not null)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(topology)!);
            File.WriteAllText(Path.Combine(addon, "Offhand.toc"), manifest);
            File.WriteAllText(topology, Stub);
        }
        return (exe, topology);
    }

    [Fact]
    public void Apply_updates_only_the_selected_install_and_does_not_rewrite_identical_bytes()
    {
        var selected = Client("_forever_");
        var sibling = Client("_retail_");
        Assert.True(OffhandBridgeStore.Write(selected.Exe, Bridge));
        Assert.Equal(Encoding.UTF8.GetBytes(Bridge), File.ReadAllBytes(selected.Topology));
        Assert.Equal(Stub, File.ReadAllText(sibling.Topology));

        File.SetLastWriteTimeUtc(selected.Topology, new DateTime(2024, 5, 2, 0, 0, 0, DateTimeKind.Utc));
        var before = File.GetLastWriteTimeUtc(selected.Topology);
        Assert.False(OffhandBridgeStore.Write(selected.Exe, Bridge));
        Assert.Equal(before, File.GetLastWriteTimeUtc(selected.Topology));
        Assert.True(OffhandBridgeStore.Write(selected.Exe, Bridge.Replace("schema = 1", "schema = 1, physicalWidth = 3840")));
        Assert.Single(Directory.GetFiles(Path.GetDirectoryName(selected.Topology)!));
    }

    [Fact]
    public void Absent_addon_is_distinct_from_a_damaged_install_and_sibling_is_never_used()
    {
        var selected = Client("_forever_", manifest: null);
        var sibling = Client("_retail_");
        Assert.Throws<OffhandAddonNotInstalledException>(() => OffhandBridgeStore.Write(selected.Exe, Bridge));
        Assert.False(Directory.Exists(Path.Combine(Path.GetDirectoryName(selected.Exe)!, "Interface")));
        Directory.CreateDirectory(Path.GetDirectoryName(selected.Topology)!);
        Assert.Throws<InvalidOperationException>(() => OffhandBridgeStore.Write(selected.Exe, Bridge));
        Assert.Equal(Stub, File.ReadAllText(sibling.Topology));
    }

    [Theory]
    [InlineData("# Core\\CompanionTopology.lua")]
    [InlineData("## X-Offhand-Companion-Protocol: 2\nCore/CompanionTopology.lua")]
    [InlineData("## X-Offhand-Topology-Schemas: 2,3\nCore/CompanionTopology.lua")]
    public void Incompatible_manifest_leaves_installed_file_intact(string manifest)
    {
        var client = Client("_forever_", manifest);
        Assert.Throws<InvalidOperationException>(() => OffhandBridgeStore.Write(client.Exe, Bridge));
        Assert.Equal(Stub, File.ReadAllText(client.Topology));
    }

    [Fact]
    public void The_selected_flavor_manifest_takes_precedence_over_the_generic_manifest()
    {
        var client = Client("_forever_");
        var addon = Directory.GetParent(Path.GetDirectoryName(client.Topology)!)!.FullName;
        File.WriteAllText(Path.Combine(addon, "Offhand_Forever.toc"), "# no topology bridge");
        Assert.Throws<InvalidOperationException>(() => OffhandBridgeStore.Write(client.Exe, Bridge));
        Assert.Equal(Stub, File.ReadAllText(client.Topology));
        File.WriteAllText(Path.Combine(addon, "Offhand_Forever.toc"), Manifest);
        File.WriteAllText(Path.Combine(addon, "Offhand.toc"), "# no topology bridge");
        Assert.True(OffhandBridgeStore.Write(client.Exe, Bridge));
    }

    [Fact]
    public void A_listed_bridge_is_created_when_absent_but_custom_addon_code_is_preserved()
    {
        var client = Client("_classic_era_");
        File.Delete(client.Topology);
        Assert.True(OffhandBridgeStore.Write(client.Exe, Bridge));
        Assert.Equal(Bridge, File.ReadAllText(client.Topology));
        var modified = Stub + "ConfigureCustomPanels()\n";
        File.WriteAllText(client.Topology, modified);
        Assert.Throws<InvalidOperationException>(() => OffhandBridgeStore.Write(client.Exe, Bridge));
        Assert.Equal(modified, File.ReadAllText(client.Topology));
    }

    [Fact]
    public void Standalone_companion_topology_can_be_replaced_on_explicit_apply()
    {
        var client = Client("_forever_");
        File.WriteAllText(client.Topology, "-- Generated by Offhand Companion. Do not edit while the Companion is running.\nOffhandCompanionTopology = {}");
        Assert.True(OffhandBridgeStore.Write(client.Exe, Bridge));
        Assert.Equal(Bridge, File.ReadAllText(client.Topology));
    }

    public void Dispose() => _root.Delete(recursive: true);
}
