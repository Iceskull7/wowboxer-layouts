using System.Globalization;
using System.Text;

namespace WoWBoxer.Layouts.Core;

/// <summary>Writes the Offhand addon's schema 1 dual-display geometry for a validated window span.</summary>
public static class OffhandTopology
{
    public static string ToLua(MonitorInfo main, MonitorInfo workspace, PixelRect span)
    {
        var game = main.Bounds;
        var screen = workspace.Bounds;
        var left = Math.Max(screen.X, span.X);
        var top = Math.Max(screen.Y, span.Y);
        var visible = new PixelRect(left, top, Math.Min(screen.Right, span.Right) - left,
            Math.Min(screen.Bottom, span.Bottom) - top);

        if (!span.Contains(game) || game.Width <= 0 || game.Height <= 0 || visible.Width <= 0 ||
            visible.Height <= 0 || game.Overlaps(visible) || main.Index == workspace.Index)
            throw new ArgumentException("The span must cover the game display and part of a separate workspace display.", nameof(span));

        // Viewport.lua reads physical pixels from the canvas's bottom-left, even for a display above the game.
        string Rect(PixelRect r) => FormattableString.Invariant(
            $"{{ x = {r.X - span.X}, y = {span.Bottom - r.Bottom}, width = {r.Width}, height = {r.Height} }}");
        var mainDevice = Quote(main.DeviceName);
        var workspaceDevice = Quote(workspace.DeviceName);
        // Only Offhand Companion supplies a companionVersion. Offhand accepts schema 1 with an unknown writer.
        return FormattableString.Invariant($$"""
            -- Generated by WoWBoxer Offhand.
            OffhandCompanionTopology = {
              schema = 1, mode = "DUAL_DISPLAY",
              physicalWidth = {{span.Width}}, physicalHeight = {{span.Height}},
              mainhandDevice = {{mainDevice}}, selectedDevices = { {{mainDevice}}, {{workspaceDevice}} },
              game = {{Rect(game)}},
              workspace = {{Rect(visible)}},
              panelScaleMetadata = {
                version = 1, game = {{Scale(main)}},
                workspaces = { workspace = {{Scale(workspace)}} },
              },
            }
            """) + "\n";
    }

    private static string Scale(MonitorInfo display)
    {
        var percent = display.ScalePercent;
        var percentField = percent is >= 25 and <= 1000 ? FormattableString.Invariant($", percent = {percent}") : "";
        return $"{{ device = {Quote(display.DeviceName)}{percentField} }}";
    }

    private static string Quote(string value)
    {
        var text = new StringBuilder().Append('"');
        foreach (char c in value)
        {
            if (c is '\\' or '"') text.Append('\\').Append(c);
            else if (char.IsControl(c)) text.Append('\\').Append(((int)c).ToString("D3", CultureInfo.InvariantCulture));
            else text.Append(c);
        }
        return text.Append('"').ToString();
    }
}
